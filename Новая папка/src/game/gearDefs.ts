/* ---------- ITEMS ---------- */
export function registerGearItems(ITEMS) {
  for (const id of GEAR_IDS) {
    const g = GEAR[id], sl = GEAR_SLOTS.find(x => x.id === g.slot);
    const fx = [];
    if (g.dmg) fx.push(`−${Math.round(g.dmg * 100)}% урона`);
    if (g.acid) fx.push(`−${Math.round(g.acid * 100)}% урона от кислоты и яда`);
    if (g.noise) fx.push(`−${Math.round(g.noise * 100)}% шума шагов`);
    if (g.cells) fx.push(`+${g.cells} ячеек инвентаря`);
    if (g.stam) fx.push(`${g.stam > 0 ? '+' : '−'}${Math.abs(Math.round(g.stam * 100))}% выносливости`);
    g.fx = fx;
    ITEMS[id] = { name: g.name, icon: g.icon, max: 1, use: null, gear: id, desc: `[${GEAR_CLASS_NAME[g.cls]} · ${sl.name}] ` + g.desc + ' [' + fx.join(' · ') + '] Наденьте в слот снаряжения («Надеть») — модель персонажа изменится.' };
  }
}
