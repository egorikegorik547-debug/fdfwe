// ---- стоимость: зависит от класса и характеристик ----
const BASE = [0, 8, 18, 32, 50, 72];
function costOf(g) {
  const score = (g.dmg || 0) * 100 + (g.acid || 0) * 50 + (g.noise || 0) * 60 + Math.max(0, g.stam || 0) * 80 + (g.cells || 0) * 4;
  const k = g.slot === 'vest' ? 1.25 : 1.1;
  const c = { scrap: Math.round(BASE[g.cls] + score * k) };
  if (g.slot === 'pack') c.wood = 1 + 2 * g.cls;                 // древесина — каркас и крепления
  if (g.slot === 'suit' && g.cls >= 2) c.band = g.cls * 2;       // ткань и обмотка
  if (g.slot === 'helmet' && g.cls >= 3) c.cable = g.cls - 2;    // проводка, лампы, приборы
  if (g.slot === 'mask' && g.cls >= 3) c.batt = g.cls - 2;       // активные фильтры, вентиляторы
  if (g.cls >= 4) c.schem = g.cls - 3;                           // промышленные схемы — только из сейфов
  return c;
}
export const COST_LABEL = { scrap: '🔩', wood: '🪵', cable: '🔌', batt: '🔋', band: '🩹', schem: '📑' };

export const GEAR: Record<string, any> = {};
for (const id of Object.keys(RAW)) {
  const g = RAW[id];
  g.tier = g.cls;
  g.icon = tint(ico(SLOT_ICON[g.slot]), g.color);
  g.cost = costOf(g);
  GEAR[id] = g;
}
export const GEAR_IDS = Object.keys(GEAR);
